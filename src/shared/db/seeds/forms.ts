interface FormField {
  key: string;
  type:
    | "short_text"
    | "long_text"
    | "single_choice"
    | "multi_choice"
    | "scale"
    | "nps"
    | "date"
    | "email"
    | "number"
    | "rating"
    /** Block divider — heading + intro prose, carries no answer. */
    | "section";
  labelEs: string;
  labelEn: string;
  required: boolean;
  options?: string[];
  scaleMin?: number;
  scaleMax?: number;
  /** marks this field's content as shareable (testimonial source) */
  shareablePhrase?: boolean;
  /** supporting text under the question, or the intro prose of a section */
  helpEs?: string;
  helpEn?: string;
  /** captions for the ends of a scale */
  minLabelEs?: string;
  minLabelEn?: string;
  maxLabelEs?: string;
  maxLabelEn?: string;
  /** "prompt" renders a full multi-line question in reading type */
  style?: "label" | "prompt";
}

